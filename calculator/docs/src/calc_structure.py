o = []
def esc(s): return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
def text(x, y, s, size=13, color='#2C2C2A', anchor='start', weight=400):
    o.append(f'<text x="{x}" y="{y}" font-size="{size}" fill="{color}" text-anchor="{anchor}" font-weight="{weight}">{esc(s)}</text>')
def box(x, y, w, h, kind, title, count, lines=()):
    f, s, t, tx = P[kind]
    o.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" fill="{f}" stroke="{s}" stroke-width="1.5"/>')
    text(x + 10, y + 20, title, 14, t, weight=600)
    if count: text(x + w - 10, y + 20, count, 13, t, 'end', 600)
    for i, l in enumerate(lines): text(x + 10, y + 38 + 16 * i, l, 12, tx)
def line(pts, label=None, lx=None, ly=None, kind='data', head=True, la='start', color=None):
    st = {'data': ('#444441', '', 1.6), 'ctl': ('#D85A30', 'stroke-dasharray="6 4"', 1.4),
          'clk': ('#7F77DD', 'stroke-dasharray="2 4"', 1.6)}[kind]
    c = color or st[0]
    d = 'M' + ' L'.join(f'{x},{y}' for x, y in pts)
    mk = f'marker-end="url(#ah_{kind})"' if head else ''
    o.append(f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{st[2]}" {st[1]} {mk}/>')
    if label:
        if lx is None: lx, ly = pts[-2][0] + 4, pts[-2][1] - 5
        text(lx, ly, label, 12, c, la)

