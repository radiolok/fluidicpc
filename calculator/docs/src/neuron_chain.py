"""Нейрон «ошибок ≤ 1» как цепочка 2И/2ИЛИ (пример k = 4, 7 элементов)."""
from svgkit import Svg, render, img

s = Svg(1100, 470, 'Нейрон «не более одного несовпадения»: цепочка на 2И и 2ИЛИ')
s.text(30, 64, 'Рельс A — «пока всё совпало»: Aₙ = Aₙ₋₁ ∧ xₙ.   Рельс B — «ошибок не больше одной»: Bₙ = (Bₙ₋₁ ∧ xₙ) ∨ Aₙ₋₁.   Элементов: 3k − 5.', 13, '#5F5E5A')
s.text(30, 84, 'xᵢ — прямой или инверсный выход ключа трубочки, в зависимости от веса +1 / −1.', 13, '#5F5E5A')
yA, yB = 170, 330
s.text(30, yA - 40, 'рельс A', 13, '#0F6E56', weight=600)
s.text(30, yB + 75, 'рельс B', 13, '#993C1D', weight=600)
def gate(x, y, kind, title, sub, cls):
    s.box(x, y - 30, 120, 60, cls, title, '', [sub], tsize=15)
s.line([(30, yA - 10), (148, yA - 10)], 'x₁', 34, yA - 16)
s.line([(30, yA + 10), (148, yA + 10)], 'x₂', 34, yA + 26)
s.line([(30, yB - 10), (148, yB - 10)], 'x₁', 34, yB - 16)
s.line([(30, yB + 10), (148, yB + 10)], 'x₂', 34, yB + 26)
gate(150, yA, 'AND', 'И', 'A₂', 'rec')
gate(150, yB, 'OR', 'ИЛИ', 'B₂', 'ctl')
s.line([(270, yA), (418, yA)])
s.line([(270, yB), (418, yB)])
gate(420, yA, 'AND', 'И', 'A₃ = A₂·x₃', 'rec')
gate(420, yB, 'AND', 'И', 'B₂·x₃', 'ctl')
s.line([(480, 100), (480, yA - 32)], 'x₃', 486, 118)
s.line([(480, yB + 75), (480, yB + 32)], 'x₃', 486, yB + 70)
s.line([(320, yA), (320, 250), (620, 250), (620, yB - 32)], 'A₂', 326, 244)
s.line([(540, yB), (558, yB)])
gate(560, yB, 'OR', 'ИЛИ', 'B₃', 'ctl')
s.line([(680, yB), (698, yB)])
gate(700, yB, 'AND', 'И', 'B₃·x₄', 'ctl')
s.line([(760, yB + 75), (760, yB + 32)], 'x₄', 766, yB + 70)
s.line([(540, yA), (900, yA), (900, yB - 32)], 'A₃', 846, yA - 6)
s.line([(820, yB), (838, yB)])
gate(840, yB, 'OR', 'ИЛИ', 'Y = B₄', 'ctl')
s.line([(960, yB), (1060, yB)], 'нейрон', 975, yB - 8)
s.text(30, 450, 'Последний элемент рельса A (A₄) не нужен. Нейрон на k пикселей: 2 + 3·(k − 2) − 1 = 3k − 5 элементов; k = 5…8 → 10…19.', 12, '#5F5E5A')
s.save(img('neuron_chain.svg')); render(img('neuron_chain.svg'), img('neuron_chain.png'))
