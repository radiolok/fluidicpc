from svgkit import Svg, P, render, img
s = Svg(1650, 900, 'Чиплет: 4 вертикальных блока в ряд на объединительной плите')

# ---- top row: panel -> B1 -> B2 -> B3 -> B4 -> panel ----
s.box(30, 120, 125, 150, 'in', 'Матрица', '', ['5×7 трубочек', '26 рабочих', '+ кнопка → B2'])
s.box(1505, 120, 125, 150, 'dsp', 'Табло', '', ['4 × 7 сегм.', '+ знак ← B2', '29 блинкеров'])
BW, GAPX, X0, Y0, BHh = 290, 47, 190, 80, 300
blocks = [('B1', 'Сетчатка', '220', 'rec', ('Дай A', ['19 ключей, нейроны 0–7'], '105'), ('Дай B', ['7 ключей, нейроны 8, 9,', '+ − × = C, шифратор'], '115'), 33),
          ('B2', 'Управление и ввод', '203', 'ctl', ('Дай A', ['автомат, регистр Y,', 'OP и знак'], '90'), ('Дай B', ['регистр X, декремент,', 'генератор фаз (23)'], '113'), 16),
          ('B3', 'АЛУ и результат', '243', 'alu', ('Дай A', ['мукс B, дополнение до 9,', 'BCD-сумматор'], '120'), ('Дай B', ['регистр R, маска A,', 'инкремент сотен/тысяч'], '123'), 25),
          ('B4', 'Индикация', '186', 'dsp', ('Дай A', ['мукс индикации, гашение,', 'дешифр. единиц и десятков'], '112'), ('Дай B', ['дешифр. сотен и тысяч,', 'резерв ≈75 мест'], '74'), 2)]
xs = []
for i, (nm, title, tot, kind, dA, dB, vias) in enumerate(blocks):
    x = X0 + i * (BW + GAPX); xs.append(x)
    f, st, t, tx = P[kind]
    s.rect(x, Y0, BW, BHh, f, st, 2, 10)
    s.text(x + 12, Y0 + 24, f'{nm}  {title}', 14, t, weight=600)
    s.text(x + BW - 12, Y0 + 24, tot, 13, t, 'end', 600)
    for j, (dn, lines, cnt) in enumerate((dA, dB)):
        yy = Y0 + 40 + j * 112
        s.rect(x + 10, yy, BW - 20, 96, '#FFFFFF', st, 1.2, 6)
        s.text(x + 20, yy + 20, dn + (' (зеркальный)' if j else ''), 13, t, weight=600)
        s.text(x + BW - 20, yy + 20, cnt, 13, t, 'end', 600)
        for k, l in enumerate(lines): s.text(x + 20, yy + 42 + 16 * k, l, 12, tx)
    s.text(x + BW / 2, Y0 + BHh - 12, f'переходы A↔B в общем пакете: {vias}', 11, tx, 'middle')
s.line([(155, 190), (X0, 190)], '26', 162, 183)
s.line([(xs[3] + BW, 190), (1505, 190)], '28', xs[3] + BW + 4, 183)
mid = Y0 + 150
for i, n in ((0, '10'), (1, '23'), (2, '25')):
    xa, xb = xs[i] + BW, xs[i + 1]
    s.line([(xa, mid), (xb, mid)])
    s.text((xa + xb) / 2, mid - 8, n, 14, '#444441', 'middle', 600)
s.line([(xs[1] + BW, mid + 40), (xs[2], mid + 40)], kind='clk')
s.text((xs[1] + BW + xs[2]) / 2, mid + 58, 'Ф1–Ф3', 11, '#534AB7', 'middle')
yb = Y0 + BHh + 22
s.line([(xs[1] + BW / 2, Y0 + BHh), (xs[1] + BW / 2, yb), (xs[3] + BW / 2, yb), (xs[3] + BW / 2, Y0 + BHh)], '10 (мимо B3)', xs[2] + 100, yb - 6)
s.text(825, Y0 - 18, 'все межблочные линии идут каналами объединительной плиты под блоками', 12, '#5F5E5A', 'middle')

# ---- cross-section (front view) ----
sx, sz = 2.0, 1.25
bx0, zb = 60, 845
s.text(30, 470, 'Разрез поперёк блоков (вид спереди, толщины условные)', 14, '#2C2C2A', weight=600)
yp_top = zb - 60 * sz
s.rect(bx0 - 20, yp_top, 265 * sx, 60 * sz, '#B5D4F4', '#378ADD', 1.2, 2)
s.text(bx0 - 10 + 265 * sx / 2, zb - 30, 'Буферная полость ≈ 5 л ← турбовентиляторы снизу', 12, '#042C53', 'middle')
yb_top = yp_top - 20 * sz
s.rect(bx0 - 20, yb_top, 265 * sx, 20 * sz, '#EEEDFE', '#7F77DD', 1.2, 2)
s.text(bx0 - 10 + 265 * sx / 2, yb_top + 17, 'объединительная плита: каналы 2×2 мм, прокладка', 11, '#26215C', 'middle')
LAY = [('cov', 3, '#D3D1C7'), ('plen', 5, '#B5D4F4'), ('elem', 8, '#FAC775'), ('r', 3, '#EEEDFE'), ('r', 3, '#CECBF6'), ('r', 3, '#EEEDFE'),
       ('elem', 8, '#FAC775'), ('plen', 5, '#B5D4F4'), ('cov', 3, '#D3D1C7')]
top = yb_top - 190 * sz
for i in range(4):
    x = bx0 + i * 61 * sx
    for nm, t, col in LAY:
        s.rect(x, top, t * sx, 190 * sz, col, '#888780', 0.6, 0)
        x += t * sx
    s.text(bx0 + i * 61 * sx + 41, top - 8, blocks[i][0], 13, '#2C2C2A', 'middle', 600)
    xr = bx0 + i * 61 * sx + 16 * sx
    s.rect(xr, yb_top - 4, 9 * sx, 8, '#26215C', '#26215C', 0, 0)
    for zz in (top + 50, top + 120, top + 190):
        x1 = bx0 + i * 61 * sx
        x2 = x1 + 41 * sx
        s.line([(x1, zz), (x1 - 14, zz)], kind='exh', width=1.6)
        s.line([(x2, zz), (x2 + 14, zz)], kind='exh', width=1.6)
for i in range(1, 4):
    gx = bx0 + i * 61 * sx - 10 * sx
    s.line([(gx, top + 20), (gx, top - 22)], kind='exh', width=1.6)
lx = bx0 + 3 * 61 * sx
LX = lx + 41 * sx + 40
for k, lab in enumerate(['наружу: крышка с вент. отверстиями', 'полость питания 5 мм, окна в стояки', 'плата элементов (элементы внутрь)', 'общий соединительный пакет H / V / H',
                         'порты на нижней кромке пакета', 'стояки питания — в боковых полях,', 'за плоскостью разреза']):
    s.text(LX, top + 20 + k * 22, lab, 12, '#2C2C2A' if k < 5 else '#185FA5')
s.raw(f'<line x1="{lx + 41*sx + 4}" y1="{top + 16}" x2="{LX - 4}" y2="{top + 16}" stroke="#888780"/>')
s.raw(f'<line x1="{lx + 16*sx + 9*sx/2}" y1="{yb_top - 4}" x2="{LX - 4}" y2="{top + 104}" stroke="#888780"/>')

# ---- summary ----
s.rect(1000, 470, 620, 330, '#F1EFE8', '#888780', 1.2, 8)
rows = [('Сигнальных линий между блоками', '68'), ('Тактовых линий (B2 → B3)', '3'),
        ('Портов на кромках B1 / B2 / B3 / B4', '36 / 40 / 51 / 63'), ('Ёмкость кромки (3 слоя, шаг 4 мм)', '≈ 140'),
        ('Самая длинная трасса в плите', '≈ 250 мм'), ('Сечение каналов плиты', '≥ 2×2 мм'),
        ('Блок, мм', '41 × 200 × 190'), ('Шаг блоков / зазор, мм', '61 / 20'), ('Основание, мм', '≈ 265 × 240'),
        ('Площадь против варианта 2×2', 'в 3,5 раза меньше'), ('Тактируются блоки', 'B2 и B3')]
for i, (a, b) in enumerate(rows):
    s.text(1015, 498 + 27 * i, a, 13)
    s.text(1605, 498 + 27 * i, b, 13, anchor='end', weight=600)
ly = 880
s.line([(1000, ly), (1040, ly)]); s.text(1050, ly + 4, 'сигналы', 12, '#444441')
s.line([(1140, ly), (1180, ly)], kind='clk'); s.text(1190, ly + 4, 'такт', 12, '#444441')
s.line([(1260, ly), (1300, ly)], kind='exh'); s.text(1310, ly + 4, 'выхлоп', 12, '#444441')
s.text(1000, 830, 'Порты B1 и B4 включают линии панели: 26 от матрицы,', 12, '#5F5E5A')
s.text(1000, 848, '28 к табло; кнопка и знак — на B2.', 12, '#5F5E5A')
s.save(img('chiplet.svg'))
render(img('chiplet.svg'), img('chiplet.png'))
