"""Пневматика струйного калькулятора: все расчёты питания одним скриптом.

Модели простые и консервативные:
  - сопло: v = Cd·√(2p/ρ), расход q = v·A, Re по гидравлическому диаметру;
  - щелевые полости: ламинарное течение между пластинами с равномерным отбором по длине;
  - короткие каналы и отверстия: Пуазейль + 1,5 динамического напора на вход/выход;
  - квадратные каналы: Δp = 28,4·μ·L·Q / a⁴.
Числа — оценки для выбора размеров, не замена продувке.

Запуск: python3 pneumatics.py
"""
import math

RHO = 1.2          # кг/м³, воздух 20 °C
MU = 1.81e-5       # Па·с
NU = 1.51e-5       # м²/с
CD = 0.85          # коэффициент расхода сопла
NOZZLE = 0.5e-3    # сторона квадратного сопла, м
P_NOM = 1000.0     # номинальное давление питания, Па

A_NOZ = NOZZLE ** 2


def nozzle(p):
    v = CD * math.sqrt(2 * p / RHO)
    return v, v * NOZZLE / NU, v * A_NOZ          # скорость, Re, расход м³/с


def lpm(q): return q * 6e4
def short_tube_dp(d, length, q, k_in=1.5):
    a = math.pi * d * d / 4; v = q / a
    return 128 * MU * length * q / (math.pi * d ** 4) + k_in * RHO * v * v / 2, v
def slot_plenum_dp(q, length, width, h):
    """Перепад в щели высотой h при равномерном отборе q по длине, подача с одного края."""
    return 12 * MU * q * length / (2 * width * h ** 3)
def square_channel_dp(a, length, q): return 28.4 * MU * length * q / a ** 4


def table(title, head, rows):
    print(f'\n{title}')
    w = [max(len(str(x)) for x in col) for col in zip(head, *rows)]
    fmt = '  '.join('{:>%d}' % x for x in w)
    print(fmt.format(*head))
    for r in rows: print(fmt.format(*r))


def main():
    # 1. сопло
    rows = []
    for p in (500, 750, 1000, 1500, 2000):
        v, re, q = nozzle(p)
        rows.append((f'{p/1000:.2f}', f'{v:.1f}', f'{re:.0f}', f'{lpm(q):.2f}'))
    table('1. Сопло 0,5×0,5 мм', ('p, кПа', 'v, м/с', 'Re', 'q, л/мин'), rows)
    print('   рабочее окно Re ≈ 800–1200; номинал 1,0 кПа')

    v, re, q = nozzle(P_NOM)
    # 2. расход
    rows = [(name, n, f'{lpm(n*q):.0f}', f'{n*q*3600:.1f}') for name, n in
            (('дай, 150 мест', 150), ('блок, 300 мест', 300), ('машина, ≈960 элементов', 960), ('все 1200 мест', 1200))]
    table('2. Расход при 1,0 кПа (не зависит от логического состояния)', ('что', 'элементов', 'л/мин', 'м³/ч'), rows)
    print(f'   полезная пневмомощность при 1200 местах: {1200*q*P_NOM:.1f} Вт')

    q_die = 150 * q
    # 3. полость дая 150×150 мм
    rows = []
    for h in (3e-3, 4e-3, 5e-3, 6e-3):
        one = slot_plenum_dp(q_die, 0.15, 0.15, h) * 1.2        # +20 % на вентиляционные втулки
        rows.append((f'{h*1e3:.0f}', f'{one:.2f}', f'{one/4:.2f}'))
    table('3. Полость дая 150×150 мм, 78 л/мин (+20 % на втулки)', ('h, мм', 'с одного бока, Па', 'с двух боков, Па'), rows)

    # 4. отверстие питания элемента
    rows = []
    for d in (1.0e-3, 1.5e-3, 2.0e-3, 2.5e-3, 3.0e-3):
        dp, _ = short_tube_dp(d, 3e-3, q)
        rows.append((f'{d*1e3:.1f}', f'{math.pi*d*d/4/A_NOZ:.0f}×', f'{dp:.1f}'))
    table('4. Отверстие питания элемента, длина 3 мм', ('Ø, мм', 'площадь/сопло', 'потери, Па'), rows)

    # 5. боковые стояки блока: 2 на блок, каждый несёт половину двух даёв
    a_riser = 0.017 * 0.035
    vr = q_die / a_riser
    print(f'\n5. Боковой стояк 17×35 мм: расход {lpm(q_die):.0f} л/мин, скорость {vr:.2f} м/с, '
          f'динамический напор {RHO*vr*vr/2:.1f} Па, потери на входе ≈ {1.5*RHO*vr*vr/2:.1f} Па')

    # 6. вентиляционные втулки: через окно активного выхода идёт весь поток элемента
    rows = []
    for d in (2.5e-3, 3.0e-3, 3.5e-3, 4.0e-3):
        dp, vv = short_tube_dp(d, 8e-3, q)
        rows.append((f'{d*1e3:.1f}', f'{vv:.2f}', f'{dp:.2f}'))
    table('6. Вентиляционная втулка, длина 8 мм, весь поток элемента', ('Ø, мм', 'v, м/с', 'противодавление, Па'), rows)

    # 7. зазоры между блоками: две стороны соседних блоков, выход вверх и в торцы
    rows = []
    for g in (15e-3, 20e-3, 25e-3):
        area = g * 0.20 + 2 * g * 0.19
        vg = 2 * q_die / area
        rows.append((f'{g*1e3:.0f}', f'{vg:.2f}', f'{RHO*vg*vg/2:.3f}'))
    table('7. Зазор между блоками (156 л/мин)', ('зазор, мм', 'v, м/с', 'напор, Па'), rows)

    # 8. каналы объединительной плиты
    rows = []
    for a in (1.0e-3, 1.5e-3, 2.0e-3, 3.0e-3):
        for length in (0.15, 0.25):
            cells = []
            for qc in (0.1, 0.2):
                dp = square_channel_dp(a, length, qc / 6e4)
                cells.append(f'{dp:.0f} Па ({dp/P_NOM*100:.1f} %)')
            rows.append((f'{a*1e3:.1f}×{a*1e3:.1f}', f'{length*1e3:.0f}', *cells))
    table('8. Канал сигнала в объединительной плите', ('сечение, мм', 'L, мм', 'q упр. 0,1 л/мин', 'q упр. 0,2 л/мин'), rows)
    print(f'   задержка распространения на 250 мм ≈ {0.25/343*1e3:.1f} мс; фаза такта 80–100 мс')

    # 9. гидрозатвор
    print(f'\n9. Гидрозатвор-маностат: глубина трубки {P_NOM/(1000*9.81)*1e3:.0f} мм воды для {P_NOM/1000:.2f} кПа')

    # 10. мотор пылесоса со сниженными оборотами (законы подобия вентиляторов)
    p_max, q_max = 25e3, 45e-3           # типовая характеристика: 25 кПа при Q=0, 45 л/с при p=0
    q_need, p_need = 11e-3, 1.5e3
    # k²·p_max·(1 − Q/(k·q_max)) = p  →  p_max·k² − p_max·Q/q_max·k − p = 0
    a_, b_, c_ = p_max, -p_max * q_need / q_max, -p_need
    k = (-b_ + math.sqrt(b_ * b_ - 4 * a_ * c_)) / (2 * a_)
    print(f'\n10. Мотор пылесоса 1–1,5 кВт: нужная точка {q_need*1e3:.0f} л/с при {p_need/1e3:.1f} кПа '
          f'→ обороты ≈ {k*100:.0f} % от номинала, мощность ≈ {k**3*100:.0f} % ({k**3*1000:.0f}–{k**3*1300:.0f} Вт)')


if __name__ == '__main__':
    main()
